export function isPolytechnic(schoolName: string): boolean {
  const lower = schoolName.toLowerCase();
  return (
    lower.includes('polytechnic') ||
    lower.includes('poly ') ||
    lower.includes('college of technology') ||
    lower.includes('yabatech') ||
    lower.includes('imt ') ||
    lower.includes('college of art') ||
    lower.includes('monotechnic')
  );
}
